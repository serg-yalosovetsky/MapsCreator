#!/bin/sh
# Один тик сбора спутниковых тайлов. Вызывается из cron несколько раз в сутки.
#
# Случайная задержка до 25 минут: иначе все запуски липнут к круглым временам и
# дают ровный суточный ритм. Заодно разводит тик с другими задачами роутера,
# которых в crontab уже полтора десятка.
sleep $(awk 'BEGIN { srand(); print int(rand() * 1500) }')

cd /mnt/hdd/satellite || exit 1
exec /usr/bin/python3 harvest.py >/dev/null 2>&1
